def ensure_default_accounts(db: Session) -> dict[str, User]:
    """Đảm bảo các tài khoản RBAC mặc định luôn tồn tại trong cơ sở dữ liệu."""
    accounts = [
        ("admin", "admin@nyvora.edu.vn", "admin123", "admin", 1850.0),
        ("teacher", "teacher@nyvora.edu.vn", "teacher123", "teacher", 1750.0),
        ("student", "student@nyvora.edu.vn", "student123", "student", 1500.0),
        ("trminhdev", "trminhdev@nyvora.edu.vn", "123456", "admin", 1680.0),
    ]
    created_map: dict[str, User] = {}
    teacher_obj = None

    for username, email, raw_pwd, role, elo in accounts:
        user = db.query(User).filter(User.username == username).first()
        if not user:
            user = User(
                username=username,
                email=email,
                hashed_password=hash_password(raw_pwd),
                role=role,
                overall_elo=elo,
            )
            db.add(user)
            db.flush()
            print(f"   ✅ Đã tạo tài khoản {role}: {username} / {raw_pwd}")
        created_map[username] = user
        if username == "teacher":
            teacher_obj = user

    # Gán teacher_id cho student nếu chưa có
    student_user = created_map.get("student")
    if student_user and teacher_obj and student_user.teacher_id is None:
        student_user.teacher_id = teacher_obj.id

    db.commit()
    return created_map


